// Builds src/globe.js for Hot or cold (Globle style): every country's outline in longitude/latitude, from
// Natural Earth 1:110m (1:50m for countries too small for it), from world-atlas (public domain / ISC), on a 0.2° grid
// with repeated points dropped, stored as whole numbers (degrees × 5) to keep the file small.
// Countries too small even for 1:50m are left out here (the game shows them as a dot at their centre).
// Run: node tools/globe.mjs (after npm run data)
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const topojson = require('topojson-client');
const { geoArea } = await import('d3-geo');
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const topos = ['110m', '50m'].map((r) => require(path.join(root, 'node_modules/world-atlas/countries-' + r + '.json')));
const countries = require(path.join(root, 'node_modules/world-countries/countries.json'));
global.window = {}; require(path.join(root, 'src/data.js'));
const ours = new Set(window.GS_DATA.countries.map((c) => c.id));
const byNum = Object.fromEntries(countries.filter((c) => c.ccn3).map((c) => [String(+c.ccn3), c.cca2.toLowerCase()]));
byNum['-99'] = null;
const out = {};
topos.forEach((topo) => topojson.feature(topo, topo.objects.countries).features.forEach((f) => {
  let id = byNum[String(+f.id)];
  if (!id && f.properties && f.properties.name === 'Kosovo') id = 'xk';
  if (!id && f.properties && /Cyprus/.test(f.properties.name || '')) id = null;
  if (!id || !ours.has(id) || !f.geometry || out[id]) return; // out[id] already set = from 1:110m
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = [];
  polys.forEach((poly) => {
    const ring = [];
    poly[0].forEach(([x, y]) => { const p = [Math.round(x * 5), Math.round(y * 5)]; const l = ring.length ? [ring[ring.length - 2], ring[ring.length - 1]] : null; if (!l || l[0] !== p[0] || l[1] !== p[1]) ring.push(p[0], p[1]); });
    if (ring.length < 8) return;
    // Rounding can flip a small ring inside out (it would then cover the rest of the globe): keep it the small way round.
    const pts = []; for (let n = 0; n < ring.length; n += 2) pts.push([ring[n] / 5, ring[n + 1] / 5]);
    if (geoArea({ type: 'Polygon', coordinates: [pts] }) > 2 * Math.PI) { const rev = []; for (let n = ring.length - 2; n >= 0; n -= 2) rev.push(ring[n], ring[n + 1]); rings.push(rev); } else rings.push(ring);
  });
  if (rings.length) out[id] = rings;
}));
const missing = [...ours].filter((id) => !out[id]);
const js = '/* Outlines for Hot or cold (Globle style), generated by tools/globe.mjs — Natural Earth 1:110m / 1:50m via world-atlas; numbers are degrees × 5. */\nwindow.GS_GLOBE = ' + JSON.stringify(out).replace(/"/g, '') + ';\n';
fs.writeFileSync(path.join(root, 'src/globe.js'), js);
console.log('globe: ' + Object.keys(out).length + ' countries, ' + Math.round(js.length / 1024) + ' KB; dots only: ' + missing.join(' '));
